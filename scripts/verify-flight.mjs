import assert from 'node:assert/strict';
import { readFile, mkdir } from 'node:fs/promises';
import { constructionSites } from '../js/construction-model.js';

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.OFFICE_URL || 'http://127.0.0.1:18773/';
const shots = process.env.SCREENSHOT_DIR || 'office-shots';
await mkdir(shots, { recursive: true });
const fixture = JSON.parse(await readFile(new URL('../data/project.json', import.meta.url)));
const expected = constructionSites(fixture.items, { includeContext: true });
const browser = await chromium.launch({ headless: true });
const results = [];
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => {
    window.flightFrames = 0;
    const raf = window.requestAnimationFrame;
    window.requestAnimationFrame = callback => raf(time => { window.flightFrames++; callback(time); });
  });
  await page.goto(base);
  await page.waitForSelector('#scene canvas:visible');
  await page.waitForFunction(() => document.querySelector('#flight-destination').options.length > 0);
  assert.equal(await page.locator('#tab-flight').getAttribute('aria-selected'), 'true');
  assert.equal(await page.locator('#flight-destination option').count(), expected.length);
  assert.equal(await page.locator('#item-count').innerText(), `${fixture.items.length} ITEMS`);
  assert.match(await page.locator('#planning-change-summary').innerText(), /First observation/);
  await page.locator('#daily-flight-panel > summary').click();
  assert.equal(await page.locator('.todays-flight').count(), 1);
  await page.locator('.todays-flight button').filter({ hasText: 'Go to site' }).first().click();
  assert.ok(await page.locator('#flight-destination').inputValue());
  await page.locator('#daily-flight-panel > summary').click();
  await page.locator('#flight-pause').click();
  await page.locator('#flight-destination').selectOption(expected[0].id);
  await page.locator('#flight-pause').click();
  await page.waitForTimeout(200);
  const frames = () => page.evaluate(() => window.flightFrames);
  const idle = await frames();
  await page.waitForTimeout(700);
  const idleFrames = await frames() - idle;
  assert.ok(idleFrames <= 12, 'ambient integration signals are bounded to 12 fps');
  await page.locator('#scene canvas:visible').focus();
  await page.keyboard.down('w'); await page.keyboard.down('d');
  const moving = await frames();
  await page.waitForTimeout(1100);
  await page.keyboard.up('w'); await page.keyboard.up('d');
  const activeFrames = await frames() - moving;
  assert.ok(activeFrames >= 5 && activeFrames <= 37, `flight rate bound: ${activeFrames}`);
  await page.locator('#flight-pause').click();
  assert.equal(await page.locator('#flight-pause').getAttribute('aria-pressed'), 'true');
  const big = expected.find(site => site.type === 'workstream' && site.active > 1);
  await page.locator('#flight-destination').selectOption(big.id);
  assert.equal(await page.locator('#flight-site-title').innerText(), big.title);
  assert.match(await page.locator('#flight-site-metrics').innerText(), new RegExp(`${big.cranes} cranes`));
  await page.locator('#flight-dock-panel > summary').click();
  assert.match(await page.locator('#planning-dock').innerText(), /Remaining actual cards/);
  assert.match(await page.locator('#planning-dock').innerText(), /Dependencies and crossovers are quoted/);
  await page.locator('#flight-dock-panel > summary').click();
  const identitySite = expected.find(site => site.items.some(item => item.fields?.Kind === 'Portfolio' && item.title === 'Portfolio: DecentCanopy'));
  await page.locator('#flight-destination').selectOption(identitySite.id);
  assert.equal(await page.locator('#flight-site-identity img').count(), 0, 'closed identity panel performs no image work');
  await page.locator('#flight-identity-panel > summary').click();
  await page.locator('#flight-site-identity img').first().waitFor({ state: 'attached' });
  assert.ok(await page.locator('#flight-site-identity img').count() > 0);
  assert.ok(await page.locator('#flight-site-identity img').count() <= 3);
  assert.match(await page.locator('#flight-site-identity').innerText(), /Artwork source/);
  await page.locator('#flight-identity-panel > summary').click();
  await page.locator('#flight-destination').selectOption(big.id);
  const paused = await frames(); await page.waitForTimeout(500);
  assert.ok(await frames() - paused <= 1);
  await page.locator('#flight-card-panel > summary').click();
  assert.equal(await page.locator('#flight-site-items button').count(), big.items.length);
  await page.locator('#flight-site-items button').first().click();
  assert.equal(await page.locator('#detail-panel').isVisible(), true);
  await page.locator('#close-detail').click();
  await page.locator('#flight-card-panel > summary').click();
  await page.locator('#motion-button').click();
  await page.locator('#flight-destination').selectOption(expected[0].id);
  await page.screenshot({ path: `${shots}/flight-desktop.png`, fullPage: true });
  // Verify refresh changes the same scene from a published fixture, never a private API.
  const next = structuredClone(fixture);
  next.exportedAt = new Date().toISOString();
  next.items[0].title = 'Portfolio: Changed through published snapshot';
  for (const item of next.items.filter(item => expected[0].items.some(member => member.id === item.id))) item.fields.Status = 'Done';
  await page.route('**/data/project.json', route => route.fulfill({ json: next }));
  await page.locator('#refresh-project').click();
  await page.waitForFunction(() => document.querySelector('#flight-site-metrics').textContent.includes('Handover'));
  assert.match(await page.locator('#flight-site-metrics').innerText(), /Handover/);
  assert.match(await page.locator('#planning-change-summary').innerText(), /marked Done/);
  const retainedComparison = await page.locator('#planning-change-summary').innerText();
  await page.locator('#refresh-project').click();
  await page.waitForFunction(() => !document.querySelector('#refresh-project').disabled);
  assert.equal(await page.locator('#planning-change-summary').innerText(), retainedComparison, 'unchanged refresh keeps last changed-publication comparison');
  await page.route('**/data/project.json', route => route.fulfill({ status: 503, body: 'Unavailable' }));
  await page.locator('#refresh-project').click();
  await page.waitForFunction(() => document.querySelector('#sync-status').textContent.includes('REFRESH FAILED'));
  assert.match(await page.locator('#flight-site-metrics').innerText(), /Handover/, 'failed refresh retains previous data explicitly');
  await page.unroute('**/data/project.json');
  await page.locator('#search').fill('no-such-construction-site-987');
  assert.equal(await page.locator('#flight-destination option').count(), 0);
  assert.match(await page.locator('#flight-site-title').innerText(), /No construction/);
  await page.locator('#search').fill('');
  await page.locator('#project-view').selectOption('kind:Milestone');
  assert.equal(await page.locator('#flight-destination option').count(), fixture.items.filter(item => item.fields.Kind === 'Milestone').length);
  await page.locator('#project-view').selectOption('');
  for (const tab of ['board', 'roadmap', 'canopy', 'passports', 'catalog', 'own', 'flight']) {
    await page.locator(`[data-tab="${tab}"]`).click();
    await page.waitForSelector('#scene canvas:visible');
    assert.equal(await page.locator('#scene canvas:visible').count(), 1, `${tab} must own one active renderer`);
  }
  await page.locator('#mode-button').click();
  assert.equal(await page.locator('.list-card').count(), fixture.items.length);
  assert.equal(await page.locator('#scene').isVisible(), false);
  assert.deepEqual(errors, []);
  results.push({ desktop: 'passed', sites: expected.length, items: fixture.items.length, idleFrames, activeFrames, dynamicRefresh: 'passed', failureRetention: 'passed', allTabs: 'passed' });
  await page.close();
  for (const width of [375, 320]) {
    const mobile = await browser.newPage({ viewport: { width, height: 900 }, isMobile: true, hasTouch: true, reducedMotion: 'reduce' });
    const mobileErrors = []; mobile.on('pageerror', error => mobileErrors.push(error.message));
    await mobile.goto(base);
    await mobile.waitForSelector('.list-card');
    assert.equal(await mobile.locator('#tab-flight').getAttribute('aria-selected'), 'true');
    assert.equal(await mobile.locator('#scene canvas').count(), 0, 'reduced/mobile first load must not import WebGL');
    await mobile.locator('#flight-next').click();
    assert.equal(await mobile.locator('#flight-site-title').innerText(), expected[1].title);
    await mobile.locator('#mode-button').click();
    await mobile.waitForSelector('#scene canvas:visible');
    await mobile.locator('#motion-button').click();
    const control = mobile.locator('[data-thrust="w"]'); await control.scrollIntoViewIfNeeded();
    const box = await control.boundingBox();
    await mobile.mouse.move(box.x + box.width / 2, box.y + box.height / 2); await mobile.mouse.down();
    await mobile.waitForTimeout(400); await mobile.mouse.up();
    assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth - innerWidth) <= 1, 'no mobile horizontal overflow');
    assert.ok(await mobile.locator('#page-title').evaluate(title => title.getBoundingClientRect().right <= innerWidth), 'landing title must fit, not merely be clipped');
    await mobile.screenshot({ path: `${shots}/flight-mobile-${width}.png`, fullPage: true });
    assert.deepEqual(mobileErrors, []);
    results.push({ width, reducedMotion: 'passed', touch: 'passed', overflow: 0 });
    await mobile.close();
  }
  console.log(JSON.stringify(results, null, 2));
} finally { await browser.close(); }
