import { execFileSync } from 'node:child_process';
import { writeFile } from 'node:fs/promises';

// Deliberate, reviewed import; runtime activity collection never expands this public allowlist.
const checkout = process.argv[2];
if (!checkout) throw new Error('Pass the reviewed Canopy checkout path.');
const revision = execFileSync('git', ['-C', checkout, 'rev-parse', `${process.argv[3] || 'origin/main'}^{commit}`], { encoding: 'utf8' }).trim();
const map = JSON.parse(execFileSync('git', ['-C', checkout, 'show', `${revision}:data/agency-map.json`], { encoding: 'utf8' }));
const projects = map.projects.filter(project => /^[\w.-]+\/[\w.-]+$/.test(project.repo || ''));
const byId = new Map(projects.map(project => [project.id, project]));
const connections = map.relationships.filter(link => byId.has(link.source) && byId.has(link.target)).map(link => ({
  from: byId.get(link.source).entityId ? `entity:${byId.get(link.source).entityId}` : byId.get(link.source).repo,
  to: byId.get(link.target).entityId ? `entity:${byId.get(link.target).entityId}` : byId.get(link.target).repo,
  kind: link.type, state: link.state || 'recorded', label: link.note || link.type,
  evidence: link.evidence || [], nextTest: link.nextTest || '',
}));
const registry = {
  source: `https://github.com/TheJollyLaMa/DecentCanopy/blob/${revision}/data/agency-map.json`,
  projects: projects.map(project => ({ repository: project.repo, name: project.name, ens: project.ens || '',
    ...(project.entityId ? { entityId: project.entityId } : {}),
    reviewedAt: project.reviewedAt || map.reviewedAt, currentState: project.currentState || '',
    nextAction: project.nextAction || '', updates: project.updates || [] })),
  connections,
};
await writeFile(new URL('../js/canopy-registry.js', import.meta.url), `// Generated by scripts/import-canopy-map.mjs from reviewed public Canopy data.\nexport const CANOPY = ${JSON.stringify(registry, null, 2)};\n`);
console.log(`Imported ${projects.length} public project references and ${connections.length} typed connections at ${revision}.`);
